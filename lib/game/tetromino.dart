import 'dart:math' show Point;

/// A board coordinate. `+x` is right, `+y` is down (screen convention).
typedef Cell = Point<int>;

/// Spawn position of every piece, in board coordinates.
const int spawnX = 3;
const int spawnY = -1;

/// The seven standard Tetris tetrominoes.
enum PieceType { i, o, t, s, z, j, l }

/// Pure geometry data for the seven tetrominoes: spawn cells, rotations,
/// Super Rotation System wall kicks and a display color per piece.
///
/// This class has no Flutter/Flame dependency so it can be used by the game
/// engine, tests, previews and tooling alike.
class Tetromino {
  const Tetromino._();

  static const int rotationCount = 4;

  /// Bounding box used when rotating a piece.
  static int boxSize(PieceType type) => switch (type) {
        PieceType.i => 4,
        PieceType.o => 2,
        _ => 3,
      };

  /// Spawn cells relative to the piece's bounding box.
  static List<Cell> spawnCells(PieceType type) => switch (type) {
        PieceType.i => const [
            Point(0, 1),
            Point(1, 1),
            Point(2, 1),
            Point(3, 1),
          ],
        PieceType.o => const [
            Point(0, 0),
            Point(1, 0),
            Point(0, 1),
            Point(1, 1),
          ],
        PieceType.t => const [
            Point(1, 0),
            Point(0, 1),
            Point(1, 1),
            Point(2, 1),
          ],
        PieceType.s => const [
            Point(1, 0),
            Point(2, 0),
            Point(0, 1),
            Point(1, 1),
          ],
        PieceType.z => const [
            Point(0, 0),
            Point(1, 0),
            Point(1, 1),
            Point(2, 1),
          ],
        PieceType.j => const [
            Point(0, 0),
            Point(0, 1),
            Point(1, 1),
            Point(2, 1),
          ],
        PieceType.l => const [
            Point(2, 0),
            Point(0, 1),
            Point(1, 1),
            Point(2, 1),
          ],
      };

  /// Suggested ARGB display color. Renderers are free to ignore this and use
  /// a monochrome LCD palette instead.
  static int color(PieceType type) => switch (type) {
        PieceType.i => 0xFF40D8DE,
        PieceType.o => 0xFFF2C94C,
        PieceType.t => 0xFFB06AD8,
        PieceType.s => 0xFF5FCB72,
        PieceType.z => 0xFFE26161,
        PieceType.j => 0xFF5A82E8,
        PieceType.l => 0xFFF2954E,
      };

  /// Cells of [type] in rotation [rotation] (0..3), relative to the piece box.
  /// Rotations are generated by rotating the spawn cells clockwise, which
  /// keeps every state inside the piece's bounding box.
  static List<Cell> cells(PieceType type, int rotation) {
    final r = ((rotation % rotationCount) + rotationCount) % rotationCount;
    var cells = spawnCells(type);
    final max = boxSize(type) - 1;
    for (var i = 0; i < r; i++) {
      cells = [for (final c in cells) Point(max - c.y, c.x)];
    }
    return cells;
  }

  /// SRS wall-kick offsets for rotating [from] -> [to], in the order they must
  /// be tried. Y offsets are already converted to screen convention (down is
  /// positive), unlike the canonical tables which use up-positive Y.
  static List<Cell> kicks(PieceType type, int from, int to) {
    // The O piece is rotationally symmetric: it never needs a kick.
    if (type == PieceType.o) return const [Point(0, 0)];
    final table = type == PieceType.i ? _iKicks : _jlstzKicks;
    return table[_key(from, to)] ?? const [Point(0, 0)];
  }

  static int _key(int from, int to) =>
      (from % rotationCount) * rotationCount + (to % rotationCount);

  static const Map<int, List<Cell>> _jlstzKicks = <int, List<Cell>>{
    0 * 4 + 1: [Point(0, 0), Point(-1, 0), Point(-1, -1), Point(0, 2), Point(-1, 2)],
    1 * 4 + 0: [Point(0, 0), Point(1, 0), Point(1, 1), Point(0, -2), Point(1, -2)],
    1 * 4 + 2: [Point(0, 0), Point(1, 0), Point(1, 1), Point(0, -2), Point(1, -2)],
    2 * 4 + 1: [Point(0, 0), Point(-1, 0), Point(-1, -1), Point(0, 2), Point(-1, 2)],
    2 * 4 + 3: [Point(0, 0), Point(1, 0), Point(1, -1), Point(0, 2), Point(1, 2)],
    3 * 4 + 2: [Point(0, 0), Point(-1, 0), Point(-1, 1), Point(0, -2), Point(-1, -2)],
    3 * 4 + 0: [Point(0, 0), Point(-1, 0), Point(-1, 1), Point(0, -2), Point(-1, -2)],
    0 * 4 + 3: [Point(0, 0), Point(1, 0), Point(1, -1), Point(0, 2), Point(1, 2)],
  };

  static const Map<int, List<Cell>> _iKicks = <int, List<Cell>>{
    0 * 4 + 1: [Point(0, 0), Point(-2, 0), Point(1, 0), Point(-2, 1), Point(1, -2)],
    1 * 4 + 0: [Point(0, 0), Point(2, 0), Point(-1, 0), Point(2, -1), Point(-1, 2)],
    1 * 4 + 2: [Point(0, 0), Point(-1, 0), Point(2, 0), Point(-1, -2), Point(2, 1)],
    2 * 4 + 1: [Point(0, 0), Point(1, 0), Point(-2, 0), Point(1, 2), Point(-2, -1)],
    2 * 4 + 3: [Point(0, 0), Point(2, 0), Point(-1, 0), Point(2, -1), Point(-1, 2)],
    3 * 4 + 2: [Point(0, 0), Point(-2, 0), Point(1, 0), Point(-2, 1), Point(1, -2)],
    3 * 4 + 0: [Point(0, 0), Point(1, 0), Point(-2, 0), Point(1, 2), Point(-2, -1)],
    0 * 4 + 3: [Point(0, 0), Point(-1, 0), Point(2, 0), Point(-1, -2), Point(2, 1)],
  };
}

/// The currently falling piece: a [PieceType] plus its board position and
/// rotation. Cells above the visible board (`y < 0`) are allowed during spawn.
class ActivePiece {
  ActivePiece(this.type, {this.x = spawnX, this.y = spawnY, this.rotation = 0});

  final PieceType type;
  int x;
  int y;
  int rotation;

  /// Absolute board coordinates occupied by this piece.
  List<Cell> get cells {
    final local = Tetromino.cells(type, rotation);
    return [for (final c in local) Cell(c.x + x, c.y + y)];
  }

  ActivePiece copy() => ActivePiece(type, x: x, y: y, rotation: rotation);

  @override
  String toString() => 'ActivePiece($type, x: $x, y: $y, r: $rotation)';
}
